/**
 * Assign Office Page
 *
 * Allows an administrator to create a new active office allocation.
 *
 * Business rules currently implemented:
 * 1. A faculty member with an active allocation is not shown.
 * 2. An office with an active allocation is not shown.
 * 3. An allocation is active when endedAt === null.
 *
 * These filters prevent normal use of this page from assigning:
 * - Multiple active offices to one faculty member.
 * - One occupied office to multiple faculty members.
 *
 * Future work:
 * The recommendation system will rank the available offices using
 * faculty rank/tenure, department building, window preference,
 * and OFFICE vs. CUBICLE.
 */

import { db } from "@/prisma/db";
import { redirect } from "next/navigation";
import { logChange } from "@/lib/history";
import {
  Button,
  ButtonLink,
  Field,
  FormCard,
  PageShell,
  selectClass,
} from "@/components/ui";


export default async function AddAllocationPage() {
  // Load all data needed to determine which faculty and offices
  // are currently available for a new assignment.
  const faculty = await db.orm.public.Faculty.all();
  const offices = await db.orm.public.Office.all();
  const allocations = await db.orm.public.Allocation.all();

  // An Allocation remains active until endedAt receives a timestamp.
  const activeAllocations = allocations.filter(
    (allocation) => allocation.endedAt === null
  );

  // Remove faculty who already have an active office assignment.
  const availableFaculty = faculty.filter(
    (member) =>
      !activeAllocations.some(
        (allocation) => allocation.facultyId === member.id
      )
  );

  // How many people are currently in each office.
  const occupants = (officeId: number) =>
    activeAllocations.filter((allocation) => allocation.officeId === officeId).length;

  // Only show offices that:
  // 1. Have AVAILABLE status
  // 2. Still have room: current occupants < capacity
  //    (a shared office with capacity 2 stays in the list until it has 2 people)
  const availableOffices = offices.filter(
    (office) => office.status === "AVAILABLE" && occupants(office.id) < office.capacity
  );

  async function assignOffice(formData: FormData) {
    "use server";

    const facultyId = Number(formData.get("facultyId"));
    const officeId = Number(formData.get("officeId"));

    // Check again on the server that the office still has room
    // (someone else may have filled it since the page loaded).
    const office = await db.orm.public.Office.where({ id: officeId }).first();
    const taken = await db.orm.public.Allocation.where({ officeId, endedAt: null }).all();
    if (!office || taken.length >= office.capacity) {
      redirect("/admin/allocations/add");
    }

    // Creating an Allocation connects one faculty member to one office.
    // assignedAt is automatically generated by the database.
    // endedAt starts as null, making this an active allocation.
    await db.orm.public.Allocation.create({
      facultyId,
      officeId,
    });

    const member = await db.orm.public.Faculty.where({ id: facultyId }).first();
    await logChange({
      action: "Assigned office",
      entity: "Allocation",
      entityId: facultyId,
      details: `${member?.firstName} ${member?.lastName} → ${office?.building}-${office?.roomNumber}`,
    });

    redirect("/admin");
  }

  return (
    <PageShell
      eyebrow="Admin · Allocations"
      title="Assign Office"
      description="Connect a faculty member with an office that still has room."
    >
      <FormCard
        title="New assignment"
        description="Only faculty without an office, and available offices with free capacity, are listed."
      >
        <form action={assignOffice} className="space-y-6">
          {/* Only faculty without an active allocation appear here. */}
          <Field label="Faculty Member" htmlFor="facultyId">
            <select
              id="facultyId"
              name="facultyId"
              required
              defaultValue=""
              className={selectClass}
            >
              <option value="" disabled>
                Select Faculty Member
              </option>

              {availableFaculty.map((member) => (
                <option key={member.id} value={member.id}>
                  {member.firstName} {member.lastName}
                </option>
              ))}
            </select>
          </Field>

          {/* Only offices with free capacity appear here. */}
          <Field label="Office" htmlFor="officeId">
            <select
              id="officeId"
              name="officeId"
              required
              defaultValue=""
              className={selectClass}
            >
              <option value="" disabled>
                Select Office
              </option>

              {availableOffices.map((office) => (
                <option key={office.id} value={office.id}>
                  {office.building} {office.roomNumber}
                  {office.capacity > 1 ? ` (${occupants(office.id)} of ${office.capacity} taken)` : ""}
                </option>
              ))}
            </select>
          </Field>

          <div className="flex flex-col-reverse gap-3 pt-2 sm:flex-row sm:justify-end">
            <ButtonLink href="/admin/allocations" variant="outline">
              View Current Allocations
            </ButtonLink>
            <Button type="submit">Assign Office</Button>
          </div>
        </form>
      </FormCard>
    </PageShell>
  );
}
